#!/usr/bin/env node
/**
 * Ensures a strong SESSION_SECRET exists for local development / local
 * production builds, so `npm run dev` and `npm start` work out of the box while
 * production deployments still fail closed (see getSessionSecret()).
 *
 *  - already set in the environment      → nothing to do
 *  - present in .env.local               → nothing to do
 *  - otherwise (local machine only)      → generate 48 bytes and append it
 *
 * Never runs on a hosted platform: Vercel/Cloudflare inject env vars and the
 * filesystem is read-only, and a per-boot random secret would invalidate every
 * staff cookie across instances.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, appendFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const hosted =
  process.env.VERCEL || process.env.CF_PAGES || process.env.NETLIFY || process.env.AWS_LAMBDA_FUNCTION_NAME;
const file = path.join(process.cwd(), '.env.local');

function hasSecretInFile() {
  if (!existsSync(file)) return false;
  return readFileSync(file, 'utf8')
    .split('\n')
    .some((line) => /^\s*SESSION_SECRET\s*=\s*\S{16,}/.test(line));
}

if (process.env.SESSION_SECRET && process.env.SESSION_SECRET.length >= 32) {
  process.exit(0);
}

if (hasSecretInFile()) {
  process.exit(0);
}

if (hosted) {
  console.warn(
    '\n⚠  SESSION_SECRET is not set. On this platform, add it to the project\n' +
      '   environment variables (>= 32 random chars, e.g. `openssl rand -base64 48`).\n' +
      '   Staff sign-in will fail until you do — by design.\n',
  );
  process.exit(0);
}

const secret = randomBytes(48).toString('base64');
try {
  const header = `\n# generated by scripts/ensure-secret.mjs — do not commit\nSESSION_SECRET=${secret}\n`;
  if (existsSync(file)) appendFileSync(file, header);
  else
    writeFileSync(
      file,
      `# Local development configuration. Never commit this file.\n` +
        `# SESSION_SECRET signs the staff session cookie.\n${header}`,
    );
  console.log('[env] generated SESSION_SECRET in .env.local');
} catch (err) {
  console.warn('[env] could not write .env.local:', err instanceof Error ? err.message : err);
}
