#!/usr/bin/env node
/**
 * Ensures the secrets local development needs exist, so `npm run dev` and
 * `npm start` work out of the box while production deployments still fail
 * closed (see getSessionSecret() and the cron route).
 *
 *  - SESSION_SECRET — signs the staff session cookie. Generated randomly.
 *  - CRON_SECRET    — protects /api/cron/housekeeping. The test suites send
 *                     'local-cron-secret-for-tests' when CRON_SECRET is not in
 *                     their own environment, so local dev uses that value.
 *                     It is a local-only convenience: set a real random
 *                     CRON_SECRET in production environment variables.
 *
 * For each secret: already set in the environment or present in .env.local
 * → nothing to do; otherwise (local machine only) → append it to .env.local.
 *
 * Never writes on a hosted platform: Vercel/Cloudflare inject env vars and
 * the filesystem is read-only, and a per-boot random secret would invalidate
 * every staff cookie across instances.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, appendFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const hosted =
  process.env.VERCEL || process.env.CF_PAGES || process.env.NETLIFY || process.env.AWS_LAMBDA_FUNCTION_NAME;
const file = path.join(process.cwd(), '.env.local');
const fileText = existsSync(file) ? readFileSync(file, 'utf8') : '';

function inFile(name, minLength) {
  return fileText
    .split('\n')
    .some((line) => new RegExp(`^\\s*${name}\\s*=\\s*\\S{${minLength},}`).test(line));
}

const missing = [];
if (!(process.env.SESSION_SECRET && process.env.SESSION_SECRET.length >= 32) && !inFile('SESSION_SECRET', 16)) {
  missing.push({
    name: 'SESSION_SECRET',
    value: randomBytes(48).toString('base64'),
    warn: 'Staff sign-in will fail until you do — by design.',
  });
}
if (!process.env.CRON_SECRET && !inFile('CRON_SECRET', 1)) {
  missing.push({
    name: 'CRON_SECRET',
    value: 'local-cron-secret-for-tests',
    warn: 'The housekeeping cron endpoint will answer 503 until you do.',
  });
}

if (missing.length === 0) {
  process.exit(0);
}

if (hosted) {
  for (const m of missing) {
    console.warn(
      `\n⚠  ${m.name} is not set. On this platform, add it to the project\n` +
        '   environment variables (>= 32 random chars, e.g. `openssl rand -base64 48`).\n' +
        `   ${m.warn}\n`,
    );
  }
  process.exit(0);
}

try {
  const lines = missing.map((m) => `${m.name}=${m.value}`).join('\n');
  const block = `\n# generated by scripts/ensure-secret.mjs — do not commit\n${lines}\n`;
  if (existsSync(file)) appendFileSync(file, block);
  else
    writeFileSync(
      file,
      `# Local development configuration. Never commit this file.\n` +
        `# SESSION_SECRET signs the staff session cookie.\n${block}`,
    );
  for (const m of missing) console.log(`[env] generated ${m.name} in .env.local`);
} catch (err) {
  console.warn('[env] could not write .env.local:', err instanceof Error ? err.message : err);
}
